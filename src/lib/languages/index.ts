function nativeName(code: LangCodeISO6393): string {
  const locale = ISO6393_TO_6391[code] ?? code
  try {
    // Unsupported locales must not silently inherit the browser's UI language.
    if (Intl.DisplayNames.supportedLocalesOf([locale]).length === 0)
      return LANG_CODE_TO_EN_NAME[code]
    return (
      new Intl.DisplayNames([locale], { type: "language", fallback: "none" }).of(locale) ??
      LANG_CODE_TO_EN_NAME[code]
    )
  } catch {
    return LANG_CODE_TO_EN_NAME[code]
  }
}

export const LANG_CODE_TO_LOCALE_NAME = Object.fromEntries(
  LANG_CODE_ISO6393_OPTIONS.map((code) => [code, nativeName(code)]),
) as Record<LangCodeISO6393, string>

